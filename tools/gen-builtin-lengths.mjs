#!/usr/bin/env node
// Writes src/runtime/js_builtin_lengths.h: V8's `length` for every builtin function lamassu has.
// Node supplies the lengths (every function on lamassu's globals, their statics and prototypes);
// build/lamassu says which of them it has. Run after adding a builtin:
//   make cli && node tools/gen-builtin-lengths.mjs
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const globals = ['Math', 'JSON', 'Object', 'Array', 'Number', 'String', 'Boolean', 'Error', 'TypeError',
  'RangeError', 'ReferenceError', 'SyntaxError', 'Promise', 'RegExp', 'Date', 'Map', 'Set', 'parseInt',
  'parseFloat', 'isNaN', 'isFinite'];
const functionsOf = (o, owner, out) => {
  for (const k of Object.getOwnPropertyNames(o)) {
    const d = Object.getOwnPropertyDescriptor(o, k);
    if (d && typeof d.value === 'function' && k !== 'constructor') out.push({ owner, name: k, length: d.value.length });
  }
};
const cand = [];
for (const g of globals) {
  const G = globalThis[g];
  if (typeof G === 'function') cand.push({ owner: '', name: g, length: G.length });
  functionsOf(G, g, cand);
  if (typeof G === 'function' && G.prototype) functionsOf(G.prototype, g + '.prototype', cand);
}
functionsOf(Function.prototype, 'Function.prototype', cand);

// lamassu reaches a prototype's methods through an instance (a primitive's have no real prototype)
const instance = { Array: '[]', String: "''", Number: '0', Boolean: 'true', Promise: 'Promise.resolve()',
  RegExp: '/a/', Date: 'new Date(0)', Map: 'new Map()', Set: 'new Set()', Object: '({})',
  Error: "new Error('')", TypeError: "new TypeError('')", RangeError: "new RangeError('')",
  ReferenceError: "new ReferenceError('')", SyntaxError: "new SyntaxError('')", Function: '(function () {})' };
let probe = 'const r = [];\nconst t = (i, f) => { try { if (typeof f() === "function") r.push(i); } catch (e) {} };\n';
cand.forEach((e, i) => {
  const base = e.owner === '' ? 'globalThis'
    : e.owner.endsWith('.prototype') ? instance[e.owner.slice(0, -'.prototype'.length)] : e.owner;
  probe += `t(${i}, () => (${base})[${JSON.stringify(e.name)}]);\n`;
});
probe += 'print(r.join(","));\n';
const dir = mkdtempSync(join(tmpdir(), 'lengths-'));
writeFileSync(join(dir, 'probe.js'), probe);
const have = execFileSync(join(root, 'build/lamassu'), [join(dir, 'probe.js')], { encoding: 'utf8' })
  .split('\n')[0].split(',').map(Number);
rmSync(dir, { recursive: true });

const rows = have.map(i => cand[i]).map(e => `    {"${e.owner}", "${e.name}", ${e.length}},`);
writeFileSync(join(root, 'src/runtime/js_builtin_lengths.h'), `/* Generated by tools/gen-builtin-lengths.mjs (Node ${process.version}): do not edit.
 * V8's \`length\` for each builtin function lamassu has, by owner ("" a global, "Math" a static,
 * "Array.prototype" a method) and name. js_builtin_lengths_apply gives them to the natives. */
#ifndef JS_BUILTIN_LENGTHS_H
#define JS_BUILTIN_LENGTHS_H

typedef struct JsBuiltinLength {
    const char *owner;
    const char *name;
    unsigned char length;
} JsBuiltinLength;

static const JsBuiltinLength js_builtin_lengths[] = {
${rows.join('\n')}
};

#endif
`);
console.log(`${rows.length} builtin lengths written`);
