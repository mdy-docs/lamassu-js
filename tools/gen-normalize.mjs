#!/usr/bin/env node
// Writes src/runtime/js_normalize_data.h: the Unicode normalization data String.prototype.normalize
// needs, from the UCD files of the Unicode version V8's ICU uses (Node 26: Unicode 17.0, as
// baru-re's ucd.h). Run with the directory holding UnicodeData.txt and
// DerivedNormalizationProps.txt for that version:
//   node tools/gen-normalize.mjs <ucd-dir>
// (https://www.unicode.org/Public/17.0.0/ucd/). Hangul syllables are algorithmic and not tabled.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '17.0.0';
const dir = process.argv[2];
if (!dir) {
  console.error('usage: node tools/gen-normalize.mjs <ucd-dir>');
  process.exit(1);
}
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ud = readFileSync(join(dir, 'UnicodeData.txt'), 'utf8');
const dnp = readFileSync(join(dir, 'DerivedNormalizationProps.txt'), 'utf8');
if (!dnp.startsWith(`# DerivedNormalizationProps-${VERSION}.txt`))
  throw new Error(`expected Unicode ${VERSION} data`);

const ccc = new Map(), dec = new Map(); // cp -> class; cp -> {compat, cps}
let rangeStart = null;
for (const line of ud.split('\n')) {
  if (!line) continue;
  const f = line.split(';');
  const cp = parseInt(f[0], 16);
  if (f[1].endsWith(', First>')) { rangeStart = cp; continue; }
  const lo = f[1].endsWith(', Last>') ? rangeStart : cp;
  for (let c = lo; c <= cp; c++) {
    if (+f[3]) ccc.set(c, +f[3]);
    if (f[5]) {
      const compat = f[5].startsWith('<');
      dec.set(c, { compat, cps: f[5].replace(/^<[^>]*> /, '').split(' ').map((h) => parseInt(h, 16)) });
    }
  }
}
const excluded = new Set();
for (const line of dnp.split('\n')) {
  const m = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*; Full_Composition_Exclusion/);
  if (!m) continue;
  for (let c = parseInt(m[1], 16); c <= parseInt(m[2] || m[1], 16); c++) excluded.add(c);
}

const full = (cp, compat) => {
  const d = dec.get(cp);
  if (!d || (d.compat && !compat)) return [cp];
  return d.cps.flatMap((c) => full(c, compat));
};
const utf16 = (cps) => cps.flatMap((c) => c > 0xffff ? [0xd800 + ((c - 0x10000) >> 10), 0xdc00 + ((c - 0x10000) & 0x3ff)] : [c]);

// decompositions: per code point, the full canonical and the full compatibility decomposition
const pool = [];
const poolIndex = new Map();
const put = (units) => {
  const key = units.join(',');
  if (poolIndex.has(key)) return poolIndex.get(key);
  const off = pool.length;
  pool.push(...units);
  poolIndex.set(key, off);
  return off;
};
const rows = [];
for (const cp of [...dec.keys()].sort((a, b) => a - b)) {
  const c = full(cp, false), k = full(cp, true);
  const cu = c.length === 1 && c[0] === cp ? [] : utf16(c), ku = utf16(k);
  const same = cu.length && cu.join() === ku.join();
  const coff = cu.length ? put(cu) : 0;
  const koff = same ? coff : put(ku);
  if (cu.length > 7 || ku.length > 31) throw new Error('decomposition too long for the packing');
  rows.push(`{0x${((cp << 8) | (cu.length << 5) | ku.length).toString(16).toUpperCase()}, ${coff}, ${koff}}`);
}
if (pool.length > 65535) throw new Error('pool too big');

// primary composites: canonical pairs not excluded from composition
const pairs = [];
for (const [cp, d] of dec) {
  if (d.compat || d.cps.length !== 2 || excluded.has(cp)) continue;
  pairs.push([d.cps[0], d.cps[1], cp]);
}
pairs.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

// combining classes as ranges of one class
const cccRows = [];
for (const cp of [...ccc.keys()].sort((a, b) => a - b)) {
  const last = cccRows[cccRows.length - 1];
  if (last && last[1] === cp - 1 && last[2] === ccc.get(cp)) last[1] = cp;
  else cccRows.push([cp, cp, ccc.get(cp)]);
}

const hex = (n) => '0x' + n.toString(16).toUpperCase();
const wrap = (items, per) => items.reduce((a, x, i) => a + (i % per ? ' ' : '\n    ') + x + ',', '');
writeFileSync(join(root, 'src/runtime/js_normalize_data.h'), `/* Generated by tools/gen-normalize.mjs from Unicode ${VERSION}: do not edit.
 * String.prototype.normalize's data (js_normalize.c). */
#ifndef JS_NORMALIZE_DATA_H
#define JS_NORMALIZE_DATA_H

#include <stdint.h>

/* Canonical_Combining_Class, nonzero ranges: [first, last, class] */
static const struct { uint32_t first, last; uint8_t ccc; } js_nf_ccc[] = {${wrap(cccRows.map(([a, b, c]) => `{${hex(a)}, ${hex(b)}, ${c}}`), 4)}
};

/* Per code point with a decomposition, sorted: key is cp << 8 | clen << 5 | klen. Its full
 * canonical decomposition is clen units at coff (clen 0 when it has only a compatibility one),
 * its full compatibility decomposition klen units at koff, as UTF-16 in js_nf_pool. */
static const struct { uint32_t key; uint16_t coff, koff; } js_nf_dec[] = {${wrap(rows, 4)}
};

static const uint16_t js_nf_pool[] = {${wrap(pool.map(hex), 12)}
};

/* Primary composites: [first, second, composite], sorted by first then second */
static const struct { uint32_t a, b, c; } js_nf_comp[] = {${wrap(pairs.map(([a, b, c]) => `{${hex(a)}, ${hex(b)}, ${hex(c)}}`), 4)}
};

#endif
`);
console.log(`${cccRows.length} class ranges, ${rows.length} decompositions, ${pool.length} pool units, ${pairs.length} composites`);
